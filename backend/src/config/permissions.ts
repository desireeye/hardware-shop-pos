export const PERMISSIONS = {
  VIEW_DASHBOARD: 'VIEW_DASHBOARD',
  CREATE_SALE: 'CREATE_SALE',
  VIEW_PRODUCTS: 'VIEW_PRODUCTS',
  CREATE_PRODUCT: 'CREATE_PRODUCT',
  EDIT_PRODUCT: 'EDIT_PRODUCT',
  DELETE_PRODUCT: 'DELETE_PRODUCT',
  CHANGE_SELLING_PRICE: 'CHANGE_SELLING_PRICE',
  CHANGE_PURCHASE_PRICE: 'CHANGE_PURCHASE_PRICE',
  VIEW_CUSTOMERS: 'VIEW_CUSTOMERS',
  CREATE_CUSTOMER: 'CREATE_CUSTOMER',
  VIEW_ORDERS: 'VIEW_ORDERS',
  CREATE_RETURN: 'CREATE_RETURN',
  VIEW_REPORTS: 'VIEW_REPORTS',
  VIEW_PROFIT: 'VIEW_PROFIT',
  MANAGE_INVENTORY: 'MANAGE_INVENTORY',
  ADJUST_STOCK: 'ADJUST_STOCK',
  VIEW_SUPPLIERS: 'VIEW_SUPPLIERS',
  MANAGE_SUPPLIERS: 'MANAGE_SUPPLIERS',
  MANAGE_SETTINGS: 'MANAGE_SETTINGS',
  MANAGE_USERS: 'MANAGE_USERS',
  EXPORT_DATA: 'EXPORT_DATA',
  VIEW_AUDIT_LOG: 'VIEW_AUDIT_LOG',
} as const;

export type PermissionKey = (typeof PERMISSIONS)[keyof typeof PERMISSIONS];

export const ROLE_PERMISSIONS: Record<'ADMIN' | 'STAFF', PermissionKey[]> = {
  ADMIN: Object.values(PERMISSIONS),
  STAFF: [
    PERMISSIONS.VIEW_DASHBOARD,
    PERMISSIONS.CREATE_SALE,
    PERMISSIONS.VIEW_PRODUCTS,
    PERMISSIONS.VIEW_CUSTOMERS,
    PERMISSIONS.CREATE_CUSTOMER,
    PERMISSIONS.VIEW_ORDERS,
    PERMISSIONS.CREATE_RETURN,
    PERMISSIONS.VIEW_SUPPLIERS,
  ],
};

export const hasPermission = (role: string, permission: PermissionKey) => {
  const roleName = role.toUpperCase();
  if (roleName === 'ADMIN') {
    return true;
  }

  return ROLE_PERMISSIONS.STAFF.includes(permission);
};
